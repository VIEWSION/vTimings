const LOCALES = { de: 'de-DE', en: 'en-GB' };

let current = normalize(readStored());

function normalize(value) {
    return LANGS.includes(value) ? value : 'de';
}

function readStored() {
    try {
        return localStorage.getItem(STORAGE_KEY);
    } catch {
        return null; // Privater Modus: dann eben ohne Erinnerung.
    }
}

export function lang() {
    return current;
}

export function locale() {
    return LOCALES[current];
}

/**
 * Setzt die Sprache und merkt sie sich für den nächsten Anmeldebildschirm.
 * Zeichnet nichts neu – das entscheidet der Aufrufer.
 */
export function setLang(value) {
    current = normalize(value);
    document.documentElement.lang = current;
    try {
        localStorage.setItem(STORAGE_KEY, current);
    } catch { /* siehe readStored() */ }
    return current;
}

/**
 * Übersetzt einen Schlüssel. `{name}`-Platzhalter werden aus `params` gefüllt.
 * Fehlt ein Schlüssel in der gewählten Sprache, greift Deutsch; fehlt er auch
 * dort, kommt der Schlüssel selbst zurück – so fällt eine Lücke sofort auf.
 */
export function t(key, params) {
    let text = STRINGS[current]?.[key] ?? STRINGS.de[key] ?? key;
    if (params) {
        for (const [name, value] of Object.entries(params)) {
            text = text.replaceAll(`{${name}}`, String(value));
        }
    }
    return text;
}

document.documentElement.lang = current;
